# Compiles src/Summit/Capture/Mirror.hlsl with fxc (Windows SDK) and writes the bytecode to
# src/Summit/Capture/MirrorShaders.cs, so Summit never compiles HLSL at run time.
# Usage: powershell -File tools\build-shaders.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$hlsl = Join-Path $root 'src\Summit\Capture\Mirror.hlsl'
$out = Join-Path $root 'src\Summit\Capture\MirrorShaders.cs'

$fxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\fxc.exe" |
    Sort-Object FullName -Descending | Select-Object -First 1
if (-not $fxc) { throw 'fxc.exe not found: install the Windows SDK.' }

function Compile([string]$entry, [string]$profile) {
    $tmp = [IO.Path]::GetTempFileName()
    & $fxc.FullName /nologo /O3 /Qstrip_reflect /Qstrip_debug /T $profile /E $entry /Fo $tmp $hlsl | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "fxc failed for $entry" }
    $bytes = [IO.File]::ReadAllBytes($tmp)
    Remove-Item $tmp
    $lines = for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        '        ' + (($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ','
    }
    return $lines -join "`r`n"
}

$vs = Compile 'VS' 'vs_4_0'
$ps = Compile 'PS' 'ps_4_0'
$code = @"
// <auto-generated>
// Generated by tools/build-shaders.ps1 from Mirror.hlsl. Do not edit by hand.
// </auto-generated>
namespace Summit.Capture;

internal static class MirrorShaders
{
    public static ReadOnlySpan<byte> Vertex =>
    [
$vs
    ];

    public static ReadOnlySpan<byte> Pixel =>
    [
$ps
    ];
}
"@
[IO.File]::WriteAllText($out, $code + "`r`n")
"Wrote $out"
